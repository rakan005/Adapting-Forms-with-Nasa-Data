CREATE TABLE farm (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120),
    latitude DECIMAL(8,5) NOT NULL,
    longitude DECIMAL(8,5) NOT NULL,
    elevation_m INTEGER,
    irrigation VARCHAR(20),
    salinity_dsm DECIMAL(8,3),
    soil_depth VARCHAR(30),
    previous_crop_code VARCHAR(40),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE decision_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farm_id BIGINT NOT NULL,
    decision_date DATE NOT NULL,
    pack_code VARCHAR(80),
    coverage_level INTEGER NOT NULL,
    ranked BOOLEAN NOT NULL,
    confidence VARCHAR(20) NOT NULL,
    farmer_action VARCHAR(20),
    farmer_crop_code VARCHAR(40),
    farmer_action_at TIMESTAMP WITH TIME ZONE,
    response_json CLOB NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_decision_farm FOREIGN KEY (farm_id) REFERENCES farm(id) ON DELETE CASCADE
);

CREATE INDEX idx_decision_farm_date ON decision_record(farm_id, decision_date DESC);
