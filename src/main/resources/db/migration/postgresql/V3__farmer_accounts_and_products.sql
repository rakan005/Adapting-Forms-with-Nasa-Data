CREATE TABLE farmer (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(120) NOT NULL,
    email VARCHAR(254) NOT NULL,
    phone VARCHAR(30),
    password_hash VARCHAR(512) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_farmer_email UNIQUE (email)
);

CREATE TABLE auth_session (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmer_id BIGINT NOT NULL,
    token_hash VARCHAR(64) NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_auth_session_token UNIQUE (token_hash),
    CONSTRAINT fk_session_farmer FOREIGN KEY (farmer_id) REFERENCES farmer(id) ON DELETE CASCADE
);
CREATE INDEX idx_session_farmer ON auth_session(farmer_id, expires_at);

ALTER TABLE farm ADD COLUMN farmer_id BIGINT;
ALTER TABLE farm ADD CONSTRAINT fk_farm_farmer FOREIGN KEY (farmer_id) REFERENCES farmer(id) ON DELETE CASCADE;
CREATE INDEX idx_farm_farmer ON farm(farmer_id, id DESC);

CREATE TABLE farmer_subscription (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmer_id BIGINT NOT NULL,
    plan_code VARCHAR(24) NOT NULL,
    status VARCHAR(24) NOT NULL,
    billing_period VARCHAR(20) NOT NULL,
    started_at TIMESTAMP WITH TIME ZONE,
    current_period_end TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_subscription_farmer FOREIGN KEY (farmer_id) REFERENCES farmer(id) ON DELETE CASCADE
);
CREATE INDEX idx_subscription_farmer ON farmer_subscription(farmer_id, created_at DESC);

CREATE TABLE farm_season (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farm_id BIGINT NOT NULL,
    crop_code VARCHAR(40) NOT NULL,
    season_label VARCHAR(80) NOT NULL,
    planting_date DATE,
    harvest_date DATE,
    status VARCHAR(20) NOT NULL,
    yield_kg DECIMAL(12,2),
    notes VARCHAR(1000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_season_farm FOREIGN KEY (farm_id) REFERENCES farm(id) ON DELETE CASCADE
);
CREATE INDEX idx_season_farm ON farm_season(farm_id, planting_date DESC);

CREATE TABLE alert_preference (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmer_id BIGINT NOT NULL UNIQUE,
    in_app_enabled BOOLEAN NOT NULL,
    weather_enabled BOOLEAN NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_alert_preference_farmer FOREIGN KEY (farmer_id) REFERENCES farmer(id) ON DELETE CASCADE
);

CREATE TABLE farmer_alert (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmer_id BIGINT NOT NULL,
    farm_id BIGINT,
    alert_type VARCHAR(40) NOT NULL,
    severity VARCHAR(20) NOT NULL,
    title VARCHAR(180) NOT NULL,
    message VARCHAR(1000) NOT NULL,
    data_source VARCHAR(80),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    read_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_alert_farmer FOREIGN KEY (farmer_id) REFERENCES farmer(id) ON DELETE CASCADE,
    CONSTRAINT fk_alert_farm FOREIGN KEY (farm_id) REFERENCES farm(id) ON DELETE CASCADE
);
CREATE INDEX idx_alert_farmer ON farmer_alert(farmer_id, created_at DESC);
