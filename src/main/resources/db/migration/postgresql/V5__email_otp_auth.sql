ALTER TABLE farmer ALTER COLUMN password_hash DROP NOT NULL;

CREATE TABLE auth_email_code (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) NOT NULL,
    purpose VARCHAR(16) NOT NULL,
    code_hash VARCHAR(64) NOT NULL,
    full_name VARCHAR(120),
    phone VARCHAR(30),
    attempt_count INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    consumed_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT chk_auth_email_code_purpose CHECK (purpose IN ('REGISTER', 'LOGIN'))
);

CREATE INDEX idx_auth_email_code_lookup ON auth_email_code(email, purpose, created_at DESC);
